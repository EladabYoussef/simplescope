#include "ssd1306_hal.h"

#define SSD1306_CMD_SET_CONTRAST_CTRL      0x81
#define SSD1306_CMD_ENTIRE_DISPLAY_RESUME  0xA4
#define SSD1306_CMD_ENTIRE_DISPLAY_ON      0xA5
#define SSD1306_CMD_NORMAL_DISPLAY         0xA6
#define SSD1306_CMD_INVERT_DISPLAY         0xA7
#define SSD1306_CMD_DISPLAY_OFF            0xAE
#define SSD1306_CMD_DISPLAY_ON             0xAF

#define SSD1306_CMD_DEACTIVATE_SCROLL      0x2E

#define SSD1306_CMD_SET_MEMORY_ADDR_MODE   0x20
#define SSD1306_ADDR_MODE_HORIZONTAL       0x00
#define SSD1306_ADDR_MODE_VERTICAL         0x01
#define SSD1306_ADDR_MODE_PAGE             0x02

#define SSD1306_CMD_SET_START_LINE         0x40
#define SSD1306_CMD_SET_SEGMENT_REMAP_OFF  0xA0
#define SSD1306_CMD_SET_SEGMENT_REMAP_ON   0xA1
#define SSD1306_CMD_SET_MULTIPLEX_RATIO    0xA8
#define SSD1306_CMD_SET_COM_SCAN_INC       0xC0
#define SSD1306_CMD_SET_COM_SCAN_DEC       0xC8
#define SSD1306_CMD_SET_DISPLAY_OFFSET     0xD3
#define SSD1306_CMD_SET_COM_PINS_CONFIG    0xDA

#define SSD1306_CMD_SET_CLOCK_DIV_RATIO    0xD5
#define SSD1306_CMD_SET_PRECHARGE_PERIOD   0xD9
#define SSD1306_CMD_SET_VCOMH_DESELECT     0xDB

#define SSD1306_CMD_SET_CHARGE_PUMP        0x8D
#define SSD1306_CHARGE_PUMP_DISABLE        0x10
#define SSD1306_CHARGE_PUMP_ENABLE         0x14

#define SSD1306_CLOCK_DIV_DEFAULT          0x80
#define SSD1306_MULTIPLEX_RATIO_64         0x3F
#define SSD1306_DISPLAY_OFFSET_NONE        0x00
#define SSD1306_COM_PINS_ALT_NO_REMAP      0x12
#define SSD1306_CONTRAST_MID               0x7F
#define SSD1306_PRECHARGE_PHASE1_2_15DCLK  0xF1
#define SSD1306_VCOMH_DESELECT_0_77VCC     0x40



void ssd1306_init(void)
{
    ssd1306_write_cmd(SSD1306_CMD_DISPLAY_OFF);

    ssd1306_write_cmd(SSD1306_CMD_SET_CLOCK_DIV_RATIO);
    ssd1306_write_cmd(SSD1306_CLOCK_DIV_DEFAULT);

    ssd1306_write_cmd(SSD1306_CMD_SET_MULTIPLEX_RATIO);
    ssd1306_write_cmd(SSD1306_MULTIPLEX_RATIO_64);

    ssd1306_write_cmd(SSD1306_CMD_SET_DISPLAY_OFFSET);
    ssd1306_write_cmd(SSD1306_DISPLAY_OFFSET_NONE);

    ssd1306_write_cmd(SSD1306_CMD_SET_START_LINE | 0x00);

    ssd1306_write_cmd(SSD1306_CMD_SET_CHARGE_PUMP);
    ssd1306_write_cmd(SSD1306_CHARGE_PUMP_ENABLE);

    ssd1306_write_cmd(SSD1306_CMD_SET_MEMORY_ADDR_MODE);
    ssd1306_write_cmd(SSD1306_ADDR_MODE_HORIZONTAL);

    ssd1306_write_cmd(SSD1306_CMD_SET_SEGMENT_REMAP_ON);
    ssd1306_write_cmd(SSD1306_CMD_SET_COM_SCAN_DEC);

    ssd1306_write_cmd(SSD1306_CMD_SET_COM_PINS_CONFIG);
    ssd1306_write_cmd(SSD1306_COM_PINS_ALT_NO_REMAP);

    ssd1306_write_cmd(SSD1306_CMD_SET_CONTRAST_CTRL);
    ssd1306_write_cmd(SSD1306_CONTRAST_MID);

    ssd1306_write_cmd(SSD1306_CMD_SET_PRECHARGE_PERIOD);
    ssd1306_write_cmd(SSD1306_PRECHARGE_PHASE1_2_15DCLK);

    ssd1306_write_cmd(SSD1306_CMD_SET_VCOMH_DESELECT);
    ssd1306_write_cmd(SSD1306_VCOMH_DESELECT_0_77VCC);

    ssd1306_write_cmd(SSD1306_CMD_ENTIRE_DISPLAY_RESUME);
    ssd1306_write_cmd(SSD1306_CMD_NORMAL_DISPLAY);

    ssd1306_write_cmd(SSD1306_CMD_DISPLAY_ON);
}